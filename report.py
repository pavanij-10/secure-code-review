
from html import escape
from pathlib import Path
from datetime import datetime


def generate_html_report(review_result, output_file="security_report.html"):
    if not review_result["success"]:
        raise ValueError(review_result.get("error", "Review failed."))

    findings = review_result["findings"]

    severity_counts = {
        "HIGH": 0,
        "MEDIUM": 0,
        "LOW": 0,
        "UNKNOWN": 0
    }
    informational_count = 0

    rows = []

    for finding in findings:
        severity = str(finding.get("severity", "UNKNOWN")).upper()

        if severity not in severity_counts:
            severity_counts["UNKNOWN"] += 1
        else:
            severity_counts[severity] += 1

        if str(finding.get("test_id", "")) == "B404":
            informational_count += 1

        rows.append(f"""
        <tr>
            <td>{escape(severity)}</td>
            <td>{escape(str(finding.get('title', 'Potential issue')))}</td>
            <td>{escape(str(finding.get('file', '')))}</td>
            <td>{escape(str(finding.get('line', '')))}</td>
           <td>{escape(str(finding.get('risk', '')))}</td>
           <td>{escape(str(finding.get('recommendation', '')))}</td>
           <td><pre>{escape(str(finding.get('secure_example', 'Not available')))}</pre></td>
        </tr>
        """)

    findings_html = "\n".join(rows) or """
        <tr><td colspan="7">No findings were reported by the scanner.</td></tr>
    """

    generated_at = datetime.now().astimezone().strftime(
        "%Y-%m-%d %H:%M %Z"
    )

    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Secure Code Review Report</title>
<style>
body {{ font-family: Arial, sans-serif; margin: 32px; color: #202938; }}
h1 {{ color: #163a63; }}
.summary {{ background: #eef4fa; padding: 16px; border-radius: 8px; }}
.stats {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(140px, 1fr)); gap: 12px; margin: 20px 0; }}
.stat {{ border: 1px solid #d8dee8; border-radius: 8px; padding: 14px; }}
.stat strong {{ display: block; font-size: 24px; margin-top: 8px; }}
.table-wrap {{ overflow-x: auto; }}
table {{ border-collapse: collapse; width: 100%; margin-top: 20px; }}
th, td {{ border: 1px solid #d8dee8; padding: 12px; text-align: left; }}
th {{ background: #163a63; color: white; }}
tr:nth-child(even) {{ background: #f6f8fb; }}
footer {{ margin-top: 24px; color: #5b6472; font-size: 13px; }}
</style>
</head>
<body>
<h1>Secure Code Review Report</h1>

<div class="summary">
<p><strong>Generated:</strong> {escape(generated_at)}</p>
<p><strong>Total reported findings:</strong> {len(findings)}</p>
<p>Severity counts reflect the scanner's original classifications.
Findings require review and verification.</p>
</div>

<div class="stats">
    <div class="stat">High severity<strong>{severity_counts["HIGH"]}</strong></div>
    <div class="stat">Medium severity<strong>{severity_counts["MEDIUM"]}</strong></div>
    <div class="stat">Low severity<strong>{severity_counts["LOW"]}</strong></div>
    <div class="stat">Unknown severity<strong>{severity_counts["UNKNOWN"]}</strong></div>
    <div class="stat">Informational explanations<strong>{informational_count}</strong></div>
</div>

<div class="table-wrap">
<table>
<thead>
<tr>
<th>Severity</th><th>Finding</th><th>File</th><th>Line</th>
<th>Risk</th><th>Recommendation</th><th>Secure Code Example</th></tr>
</thead>
<tbody>
{findings_html}
</tbody>
</table>
</div>

<footer>Generated by Secure Code Review Assistant.</footer>
</body>
</html>
"""

    destination = Path(output_file).resolve()
    destination.write_text(html, encoding="utf-8")
    return destination
